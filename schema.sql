-- 6. Caja Sesiones
CREATE TABLE caja_sesiones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_apertura TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    fecha_cierre TIMESTAMP WITH TIME ZONE,
    monto_inicial NUMERIC(10,2) NOT NULL DEFAULT 0.0,
    monto_cierre NUMERIC(10,2),
    usuario_id UUID REFERENCES usuarios(id),
    estado TEXT DEFAULT 'ABIERTA'
);

-- 7. Caja Movimientos
CREATE TABLE caja_movimientos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caja_sesion_id BIGINT NOT NULL REFERENCES caja_sesiones(id),
    tipo TEXT NOT NULL,
    monto NUMERIC(10,2) NOT NULL,
    metodo_pago TEXT NOT NULL,
    descripcion TEXT,
    usuario_id UUID REFERENCES usuarios(id),
    fecha TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 8. Ventas
CREATE TABLE ventas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id),
    caja_sesion_id BIGINT NOT NULL REFERENCES caja_sesiones(id),
    usuario_id UUID REFERENCES usuarios(id),
    fecha TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    subtotal NUMERIC(10,2) NOT NULL,
    descuento_total NUMERIC(10,2) NOT NULL DEFAULT 0.0,
    total NUMERIC(10,2) NOT NULL,
    metodo_pago TEXT NOT NULL,
    tipo_comprobante TEXT DEFAULT 'TICKET',
    estado_afip TEXT DEFAULT 'PENDIENTE',
    nro_comprobante_afip TEXT,
    estado TEXT DEFAULT 'COMPLETADA'
);

-- 9. Promociones
CREATE TABLE promociones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_barras TEXT UNIQUE,
    nombre TEXT NOT NULL,
    precio_fijo NUMERIC(10,2) NOT NULL,
    activa BOOLEAN DEFAULT true
);

-- 10. Ventas Detalle
CREATE TABLE ventas_detalle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id BIGINT NOT NULL REFERENCES ventas(id),
    producto_id BIGINT REFERENCES productos(id),
    promocion_id BIGINT REFERENCES promociones(id),
    cantidad NUMERIC(10,2) NOT NULL,
    precio_unitario NUMERIC(10,2) NOT NULL,
    costo_unitario NUMERIC(10,2) NOT NULL DEFAULT 0.0,
    subtotal NUMERIC(10,2) NOT NULL
);

-- 11. Promocion Detalles
CREATE TABLE promocion_detalles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    promocion_id BIGINT NOT NULL REFERENCES promociones(id),
    producto_id BIGINT NOT NULL REFERENCES productos(id),
    cantidad_requerida INTEGER NOT NULL
);

-- 12. Cta Cte Movimientos
CREATE TABLE cta_cte_movimientos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id),
    caja_sesion_id BIGINT REFERENCES caja_sesiones(id),
    venta_id BIGINT REFERENCES ventas(id),
    usuario_id UUID REFERENCES usuarios(id),
    fecha TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    tipo TEXT NOT NULL,
    monto NUMERIC(10,2) NOT NULL,
    detalle TEXT
);

-- 13. Cta Cte Proveedores
CREATE TABLE cta_cte_proveedores_movimientos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id BIGINT NOT NULL REFERENCES proveedores(id),
    caja_sesion_id BIGINT REFERENCES caja_sesiones(id),
    fecha TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    tipo TEXT NOT NULL,
    monto NUMERIC(10,2) NOT NULL,
    detalle TEXT
);

-- SEGURIDAD (Row Level Security - RLS)
ALTER TABLE usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE productos ENABLE ROW LEVEL SECURITY;
ALTER TABLE ventas ENABLE ROW LEVEL SECURITY;

-- Políticas de seguridad para bloquear a empleadas

-- (Por defecto permitiremos leer todo a todos los autenticados para no trabar el sistema de UI local)
CREATE POLICY "Lectura libre para usuarios logueados" ON productos FOR SELECT TO authenticated USING (true);
CREATE POLICY "Lectura libre para usuarios logueados" ON ventas FOR SELECT TO authenticated USING (true);

-- Solo la admin puede borrar o alterar productos
CREATE POLICY "Solo admin edita/borra productos" ON productos FOR ALL TO authenticated 
USING (
    (SELECT rol FROM usuarios WHERE id = auth.uid()) = 'admin'
);

-- Empleadas pueden crear ventas, pero no borrarlas
CREATE POLICY "Todos pueden crear ventas" ON ventas FOR INSERT TO authenticated WITH CHECK (true);

CREATE POLICY "Solo admin edita ventas" ON ventas FOR UPDATE TO authenticated 
USING (
    (SELECT rol FROM usuarios WHERE id = auth.uid()) = 'admin'
);
CREATE POLICY "Solo admin borra ventas" ON ventas FOR DELETE TO authenticated 
USING (
    (SELECT rol FROM usuarios WHERE id = auth.uid()) = 'admin'
);
