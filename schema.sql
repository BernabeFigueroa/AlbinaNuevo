-- Esquema para AlbinaNuevo en PostgreSQL (Supabase)

-- 1. Usuarios / Roles (Extiende la autenticación de Supabase)
CREATE TABLE usuarios (
    id UUID REFERENCES auth.users(id) PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    username TEXT UNIQUE,
    nombre TEXT NOT NULL,
    rol TEXT NOT NULL CHECK (rol IN ('admin', 'empleada')),
    activo BOOLEAN DEFAULT true
);

-- 2. Categorías
CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL UNIQUE
);

-- 3. Proveedores
CREATE TABLE proveedores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    telefono TEXT,
    direccion TEXT,
    activo BOOLEAN DEFAULT true
);

-- 4. Productos
CREATE TABLE productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_barras TEXT UNIQUE,
    codigo_fabrica TEXT,
    nombre TEXT NOT NULL,
    costo_lista NUMERIC(10,2) NOT NULL DEFAULT 0.0,
    flete NUMERIC(10,2) NOT NULL DEFAULT 0.0,
    costo_final NUMERIC(10,2) NOT NULL DEFAULT 0.0,
    utilidad_porcentaje NUMERIC(5,2) NOT NULL DEFAULT 0.0,
    precio_contado NUMERIC(10,2) NOT NULL DEFAULT 0.0,
    precio_tarjeta NUMERIC(10,2) NOT NULL DEFAULT 0.0,
    stock_actual NUMERIC(10,2) NOT NULL DEFAULT 0.0,
    stock_minimo NUMERIC(10,2) NOT NULL DEFAULT 5.0,
    stock_maximo NUMERIC(10,2) NOT NULL DEFAULT 100.0,
    unidades_bulto INTEGER DEFAULT 1,
    ubicacion TEXT,
    talle TEXT,
    observaciones TEXT,
    creado_por UUID REFERENCES usuarios(id),
    modificado_por UUID REFERENCES usuarios(id),
    categoria_id BIGINT REFERENCES categorias(id),
    proveedor_id BIGINT REFERENCES proveedores(id),
    activo BOOLEAN DEFAULT true
);

-- 5. Clientes
CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    cuit TEXT,
    domicilio TEXT,
    localidad TEXT,
    provincia TEXT,
    condicion_iva TEXT DEFAULT 'Consumidor Final',
    telefono TEXT,
    condicion_pago TEXT DEFAULT 'Contado',
    descuento_porcentaje NUMERIC(5,2) DEFAULT 0.0,
    activo BOOLEAN DEFAULT true
);

